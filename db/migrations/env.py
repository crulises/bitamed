"""Alembic environment.

Runs over a synchronous psycopg2 connection, not the asyncpg driver the app
uses at runtime: asyncpg's extended query protocol refuses to execute more
than one statement per call, and these migrations wrap whole hand-written
.sql files as a single op.execute(). psycopg2 (dev-only dependency, see
requirements.txt) has no such restriction.
"""

from logging.config import fileConfig

from alembic import context
from sqlalchemy import engine_from_config, pool

from app.config import settings

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# No SQLAlchemy models are autogenerated against: app/models mirrors only
# the subset of schema.sql the application code touches (see CLAUDE.md),
# so a full autogenerate diff here would propose dropping everything else.
target_metadata = None


def _sync_url() -> str:
    return settings.database_url.replace("postgresql+asyncpg://", "postgresql+psycopg2://")


def run_migrations_offline() -> None:
    context.configure(
        url=_sync_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    configuration = config.get_section(config.config_ini_section) or {}
    configuration["sqlalchemy.url"] = _sync_url()
    connectable = engine_from_config(
        configuration,
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
